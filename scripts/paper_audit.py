"""Where does a given train.py command differ from the SLSRec paper?

Takes exactly the flags you would pass to train.py, resolves them the way
train.py does, and classifies every setting the paper talks about:

    MATCH        the paper states it and the code agrees
    MISMATCH     the paper states it, the code differs, and a flag fixes it
    AMBIGUOUS    the paper is internally inconsistent or silent on a detail
                 that changes results; the code picks one reading, a flag
                 selects the other
    ADDED        present in the code, absent from the paper
    STRUCTURAL   differs from the paper and no flag changes it
    UNSPECIFIED  the paper never says; the value is inherited from LRURec or
                 RecBLR (not a mismatch, but undocumented by the paper)

Exit code 1 if any MISMATCH remains, i.e. the command is not paper-standard.

    python scripts/paper_audit.py --dataset_code=ml-1m
    python scripts/paper_audit.py --dataset_code=ml-1m --num_epochs=1000 \
        --val_strategy=epoch --val_epochs=5
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from datasets import DATASETS                        # noqa: F401,E402 (import order)
import config as cfg                                 # noqa: E402

ORDER = ['MISMATCH', 'AMBIGUOUS', 'STRUCTURAL', 'ADDED', 'UNSPECIFIED', 'MATCH']


def resolve(argv):
    flags = list(argv)
    if not any(f.startswith('--dataset_code') for f in flags):
        flags.append('--dataset_code=ml-1m')
    if not any(f.startswith('--model_code') for f in flags):
        flags.append('--model_code=slsrec')
    a = cfg.parser.parse_args(flags)
    cfg.set_template(a)
    return a


def audit(a):
    rows = []

    def add(status, section, item, paper, code, note=''):
        rows.append((status, section, item, str(paper), str(code), note))

    per_epoch = {'ml-1m': 56}.get(a.dataset_code)

    # ------------------------------------------------------------------ #
    # Sec. IV-A4 -- training schedule
    # ------------------------------------------------------------------ #
    add('MATCH' if a.num_epochs == 1000 else 'MISMATCH', 'IV-A4', 'max epochs', 1000,
        a.num_epochs, '' if a.num_epochs == 1000 else 'fix: --num_epochs=1000')

    paper_cadence = a.val_strategy == 'epoch' and a.val_epochs == 5
    if a.val_strategy == 'epoch':
        cadence = f'every {a.val_epochs} epoch(s)'
        span = a.val_epochs * a.early_stopping_patience
    else:
        cadence = f'every {a.val_iterations} iters'
        if per_epoch:
            cadence += f' (= {a.val_iterations / per_epoch:.2f} epochs)'
        span = (a.val_iterations / per_epoch * a.early_stopping_patience) if per_epoch else None
    add('MATCH' if paper_cadence else 'MISMATCH', 'IV-A4', 'validation cadence',
        'every 5 epochs', cadence,
        '' if paper_cadence else 'fix: --val_strategy=epoch --val_epochs=5')
    add('MATCH' if a.early_stopping_patience == 10 else 'MISMATCH', 'IV-A4',
        'early-stopping patience (rounds)', 10, a.early_stopping_patience)
    if span is not None:
        add('MATCH' if abs(span - 50) < 1e-9 else 'MISMATCH', 'IV-A4',
            'patience in epochs (derived)', 50, f'{span:.0f}',
            '' if abs(span - 50) < 1e-9 else 'follows from the cadence')
    add('MATCH' if a.best_metric == 'Recall@10' else 'MISMATCH', 'IV-A4', 'model selection',
        'val Recall@10', a.best_metric)
    ok = (a.optimizer == 'AdamW' and a.lr == 0.001 and a.weight_decay == 0.01
          and not a.enable_lr_schedule and not a.enable_lr_warmup)
    add('MATCH' if ok else 'MISMATCH', 'IV-A4', 'optimizer',
        'AdamW, constant lr 1e-3, wd 1e-2',
        f'{a.optimizer}, lr {a.lr}, wd {a.weight_decay}, sched={a.enable_lr_schedule}')
    add('MATCH' if a.bert_hidden_units == 64 else 'MISMATCH', 'IV-A4', 'embedding dim D', 64,
        a.bert_hidden_units)
    add('MATCH' if a.train_batch_size == 128 else 'MISMATCH', 'IV-A4', 'batch size', 128,
        a.train_batch_size)

    # ------------------------------------------------------------------ #
    # Sec. IV-A1 / IV-E -- data and per-dataset hyperparameters
    # ------------------------------------------------------------------ #
    want_len = 200 if a.dataset_code == 'ml-1m' else 50
    add('MATCH' if a.bert_max_len == want_len else 'MISMATCH', 'IV-A1', 'max sequence length',
        want_len, a.bert_max_len)
    add('MATCH' if (a.min_uc, a.min_sc, a.split) == (5, 5, 'leave_one_out') else 'MISMATCH',
        'IV-A1', 'filtering / split', '5-core, leave-one-out',
        f'min_uc={a.min_uc} min_sc={a.min_sc} {a.split}',
        'dataset.pkl regenerated byte-identical from ratings.dat')
    want_drop = cfg.SLSREC_DROPOUT.get(a.dataset_code)
    add('MATCH' if want_drop is not None and abs(a.bert_dropout - want_drop) < 1e-9 else 'MISMATCH',
        'IV-E1', 'dropout', f'{want_drop} (Figs. 6/7)', a.bert_dropout)
    add('MATCH' if a.perturbation_probability == 0.1 else 'MISMATCH', 'IV-E2', 'theta', 0.1,
        a.perturbation_probability)
    want_alpha = 0.01 if a.dataset_code == 'beauty' else 0.3
    add('MATCH' if abs(a.uncertainty_alpha - want_alpha) < 1e-9 else 'MISMATCH', 'IV-E3', 'alpha',
        want_alpha, a.uncertainty_alpha)
    add('MATCH' if a.uncertainty_beta == 0 else 'MISMATCH', 'III-C3', 'beta', 0,
        a.uncertainty_beta)

    # ------------------------------------------------------------------ #
    # Sec. III-B -- architecture
    # ------------------------------------------------------------------ #
    add('MATCH' if a.slsrec_expand == 2 else 'MISMATCH', 'III-B2', 'd = 2D', 2, a.slsrec_expand)
    eq3 = a.use_sam_gate and a.sam_conv and a.gate_mode == 'sum'
    add('MATCH' if eq3 else 'MISMATCH', 'III-B2', 'eq.(3) G = SAM + Conv1-D1',
        'sum of both terms', f'sam={a.use_sam_gate} conv={a.sam_conv} gate_mode={a.gate_mode}',
        '' if eq3 else 'fix: --gate_mode=sum --use_sam_gate=true --sam_conv=true')
    add('MATCH' if a.fusion_mode == 'mul' else 'MISMATCH', 'III-B2', 'eq.(6) G (*) H',
        'element-wise product', a.fusion_mode, '' if a.fusion_mode == 'mul' else 'fix: --fusion_mode=mul')
    add('MATCH' if a.sam_conv_activation == 'none' else 'MISMATCH', 'III-B2',
        'eq.(3) activation on Conv1-D1', 'none', a.sam_conv_activation)
    add('MATCH' if a.sam_num_heads == 1 else 'MISMATCH', 'III-B2', 'eq.(8) attention heads', 1,
        a.sam_num_heads)
    add('MATCH' if a.use_bdlru else 'MISMATCH', 'III-B2', 'eq.(5) BD-LRU', 'on', a.use_bdlru)
    add('MATCH' if a.bdlru_c == 8 else 'MISMATCH', 'III-B2', 'eq.(11) c', 8, a.bdlru_c)
    # The configured range is checked at r_t = 1 (RecBLR's convention).  At
    # initialisation r_t = sigmoid(~0) = 0.5, so the *realised* a_t is roughly
    # the square root of that grid: measured [0.9485, 0.9995] on ML-1M.
    if (a.bdlru_r_min, a.bdlru_r_max) == (0.9, 0.999):
        add('AMBIGUOUS', 'III-B2', 'a_t init range', '"a_t uniform in [0.9, 0.999] as in [17],[35]"',
            f'base coefficient [{a.bdlru_r_min}, {a.bdlru_r_max}] at r_t=1 ({a.bdlru_lambda_init})',
            'realised a_t at init is ~[0.949, 0.9995] because r_t ~ 0.5. "as in [17]" '
            'points to RecBLR, which calibrates at r_t=1 with linspace -- what the code does. '
            'Low impact: lambda is learned (it shrank ~19% in the ML-1M run)')
    else:
        add('MISMATCH', 'III-B2', 'a_t init range', '[0.9, 0.999]',
            f'[{a.bdlru_r_min}, {a.bdlru_r_max}]', 'fix: --bdlru_r_min=0.9 --bdlru_r_max=0.999')
    add('MATCH', 'III-C2', 'eq.(20) dropout placement', 'LN(Dropout(PFFN(xc) + xc)) as printed',
        'UncertaintyPFFNBlock (printed form)',
        'chosen 2026-10-06 (audit_2026-10-06/eq20_fix.md). Identical to LN(Dropout(PFFN)+xc) '
        'at eval; differs only in training. Runs before that date used the other form')
    add('MATCH' if a.use_perturbation else 'MISMATCH', 'III-C1', 'perturbation injection', 'on',
        a.use_perturbation)
    add('MATCH' if a.use_uncertainty else 'MISMATCH', 'III-C2', 'uncertainty scaling', 'on',
        a.use_uncertainty)

    # ------------------------------------------------------------------ #
    # Genuine ambiguities
    # ------------------------------------------------------------------ #
    if a.uncertainty_loss == 'approx':
        add('AMBIGUOUS', 'III-C2', 'L_Unc form', 'eq.(24) uses the eq.(22) approx; eq.(21) defines it exactly',
            'approx (eq.24, literal)',
            'with beta=0 sigma^2 runs to the clamp: L_unc -> 0.0017, U branch dead. '
            'alt: --uncertainty_loss=exact (kept U alive, halved the NDCG@20 gap)')
    else:
        add('AMBIGUOUS', 'III-C2', 'L_Unc form', 'eq.(24) uses the eq.(22) approx; eq.(21) defines it exactly',
            'exact (eq.21)',
            'not the literal final equation (24), but the only form under which U stays '
            'active. alt: --uncertainty_loss=approx')
    add('AMBIGUOUS', 'III-B4', 'item bias in prediction',
        'eq.(15) none; LRURec eq.(10) has b_o', f'use_item_bias={a.use_item_bias}',
        'SLSRec says it is built on the LRURec repo, whose head has the bias. '
        f'alt: --use_item_bias={str(not a.use_item_bias).lower()}')

    # ------------------------------------------------------------------ #
    # Added / structural
    # ------------------------------------------------------------------ #
    clamp = a.uncertainty_logvar_clamp
    binds = 'binds under approx (that is where sigma^2 gets pinned)' if a.uncertainty_loss == 'approx' \
        else 'never binds under exact'
    add('ADDED', 'III-C2', 'clamp on Log(sigma^2)', 'none', f'+-{clamp}' if clamp else 'off',
        f'numerical safety; {binds}. disable: --uncertainty_logvar_clamp=0')
    add('STRUCTURAL', 'III-C', 'training target', 'eq.(15)/(16): last position only',
        'every position (LRURec harness)',
        'the paper says it is built on LRURec, which trains per position; eq.(20) follows')
    add('STRUCTURAL', 'III-C1', 'perturbation on padding', 'not discussed', 'never perturbed',
        'perturbing pad tokens would contradict the harness masking')
    add('STRUCTURAL', 'III-B4', 'softmax support during training', 'eq.(15): items I',
        '|I|+1 classes (padding id 0 included)',
        'LRURec harness. Pad is never a target, so its logit is pushed down; at eval it is '
        'masked to -1e9. Negligible effect')

    # ------------------------------------------------------------------ #
    # Not in the paper -- inherited
    # ------------------------------------------------------------------ #
    add('UNSPECIFIED', 'III-B', 'number of layers L', '"stacked L layers", no value',
        a.bert_num_blocks, 'LRURec')
    add('UNSPECIFIED', 'III-B2', 'conv kernel size', 'not given', a.slsrec_d_conv, 'RecBLR')
    add('UNSPECIFIED', 'III-B2', 'activation after Conv1-D2', 'not given', a.bdlru_conv_activation,
        'RecBLR')
    add('UNSPECIFIED', 'III-B2', 'weight decay on lambda', 'not given',
        'excluded' if getattr(a, 'exclude_lambda_from_decay', False) else 'decayed', 'LRURec convention')
    add('UNSPECIFIED', 'IV-A4', 'AdamW epsilon', 'not given', a.adam_epsilon, 'LRURec')
    add('UNSPECIFIED', 'IV-A4', 'gradient clipping', 'not given', a.max_grad_norm, 'LRURec')
    add('UNSPECIFIED', 'IV-A4', 'weight init', 'not given', 'trunc. normal, std 0.02', 'LRURec')
    add('UNSPECIFIED', 'III-B2', 'attention dropout', 'not given', a.sam_attn_dropout, '')
    add('UNSPECIFIED', 'IV-A3', 'already-seen items at eval', 'not given', 'removed', 'LRURec')
    add('UNSPECIFIED', 'IV', 'seed / number of seeds', 'not given', a.seed, '')
    return rows


def main():
    argv = sys.argv[1:]
    a = resolve(argv)
    rows = audit(a)

    print(f'\nCommand: train.py {" ".join(argv) if argv else "(defaults)"}')
    print(f'Resolved: dataset={a.dataset_code}  model={a.model_code}  seed={a.seed}\n')
    for status in ORDER:
        group = [r for r in rows if r[0] == status]
        if not group:
            continue
        print(f'--- {status} ({len(group)}) ' + '-' * (60 - len(status)))
        for _, sec, item, paper, code, note in group:
            print(f'  [{sec:<6}] {item:<32} paper: {paper:<34} code: {code}')
            if note:
                print(f'  {"":<41} -> {note}')
        print()

    n_bad = sum(1 for r in rows if r[0] == 'MISMATCH')
    counts = ', '.join(f'{s} {sum(1 for r in rows if r[0] == s)}' for s in ORDER)
    print('=' * 78)
    print(counts)
    if n_bad:
        print(f'NOT paper-standard: {n_bad} mismatch(es), each fixable with the flag shown.')
    else:
        print('Paper-standard: every setting the paper states is matched.  The AMBIGUOUS '
              'rows are\nreadings the paper does not settle -- read them before comparing numbers.')
    print('=' * 78)
    return 1 if n_bad else 0


if __name__ == '__main__':
    sys.exit(main())
